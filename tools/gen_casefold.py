#!/usr/bin/env python3
"""Generates src/ZBCaseFold.c's table (src/ZBCaseFoldTable.inc) from Unicode's
full case folding (CaseFolding.txt statuses C and F; S is the simple folding
that F supersedes, and str.casefold() applies C+F, so U+1E9E folds to "ss"), as
exposed by Python's str.casefold() (Unicode data of the interpreter running
this script).

The committed table was built with Unicode 16.0.0. The script exits non-zero
under any other Unicode version, so an older or newer Python cannot silently
change the table. To regenerate, use a Python whose unicodedata.unidata_version
is 16.0.0 (Python 3.13), or, when moving to a newer Unicode, change
EXPECTED_UNICODE_VERSION below on purpose and review the diff:

    python3 tools/gen_casefold.py > src/ZBCaseFoldTable.inc
"""
import sys
import unicodedata

EXPECTED_UNICODE_VERSION = "16.0.0"

if unicodedata.unidata_version != EXPECTED_UNICODE_VERSION:
    sys.stderr.write("gen_casefold.py: Unicode data is %s, the committed table was built with %s; "
                     "use a Python with that version (see the docstring).\n"
                     % (unicodedata.unidata_version, EXPECTED_UNICODE_VERSION))
    sys.exit(1)

print("/* Generated by tools/gen_casefold.py from Unicode %s full case folding"
      " (CaseFolding.txt C+F). Do not edit. */" % unicodedata.unidata_version)
n = 0
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    folded = chr(cp).casefold()
    if folded == chr(cp):
        continue
    cps = [ord(c) for c in folded]
    cps += [0] * (3 - len(cps))
    print("    {0x%05X, {0x%04X, 0x%04X, 0x%04X}}," % (cp, *cps))
    n += 1
sys.stderr.write("%d entries\n" % n)
